INTO videos (channel_id, title, video_url, upload_date)
SELECT channel_id,
       title,

       'http://url.com/vid-' || substr(md5(random()::text), 1, 10),
       CURRENT_TIMESTAMP - ((random() * 350 + 10) || ' days')::interval
FROM unique_videos_pool
ORDER BY random()
LIMIT floor(random() * 20 + 50);

INSERT INTO subscriptions (subscriber_channel_id, target_channel_id)
SELECT c1.channel_id, c2.channel_id
FROM channels c1
         CROSS JOIN channels c2
WHERE c1.channel_id != c2.channel_id
ORDER BY random()
LIMIT floor(random() * 15 + 15);

INSERT INTO video_likes (channel_id, video_id, liked_at)
SELECT c.channel_id,
       v.video_id,
       v.upload_date + (random() * 200 || ' hours')::interval
FROM channels c
         CROSS JOIN videos v
WHERE random() > 0.4;

