SELECT g.code                  AS group_code,
       c.name                  AS course_name,
       COUNT(cl.student_id)    AS students_count,
       ROUND(AVG(cl.grade), 2) AS avg_grade
FROM "group" g
         CROSS JOIN course c
         LEFT JOIN student s
                   ON s.group_id = g.id
         LEFT JOIN course_listeners cl
                   ON cl.student_id = s.id
                       AND cl.course_id = c.id
GROUP BY g.code, c.name
ORDER BY g.code, c.name;

/*
ОБОСНОВАНИЕ ВЫБРАННЫХ ВИДОВ JOIN:
1. CROSS JOIN между таблицами "group" и course используется для генерации
   полной матрицы всех возможных сочетаний учебных групп и курсов (декартово произведение),
   что гарантирует попадание в отчёт абсолютно всех групп и курсов.
2. Последовательные LEFT JOIN с таблицами student и course_listeners
   аккуратно подтягивают информацию о студентах группы и их записях на курсы.
   Использование внешних соединений (LEFT JOIN) предотвращает исчезновение
   пустых групп и курсов, у которых нет записей.
3. Функция COUNT(cl.student_id) подсчитывает только реально записанных студентов
   (автоматически игнорируя NULL для пустых групп или незаписанных студентов),
   обеспечивая корректный вывод нулевых значений.

ОПИСАНИЕ ОДНОЙ СТРОКИ РЕЗУЛЬТАТА:
Каждая строка результирующего отчёта отображает сводную информацию
по конкретной учебной группе и конкретному учебному курсу, содержащую:
- Код учебной группы (group_code).
- Название учебного курса (course_name).
- Количество студентов из данной группы, записанных на данный курс (students_count).
- Среднюю итоговую оценку студентов этой группы по данному курсу (avg_grade).
*/